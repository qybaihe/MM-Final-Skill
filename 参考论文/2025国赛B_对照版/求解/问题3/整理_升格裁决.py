def read(path):
    return json.loads(Path(path).read_text())


def write(path, payload):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def text(path, value):
    Path(path).write_text(value)


def append_events(events):
    path = ROOT / "交接/实验记录.json"
    existing = read(path) if path.exists() else []
    assert isinstance(existing, list)
    prohibited = [line.strip() for line in (ROOT / "运行时/流程词.txt").read_text().splitlines() if line.strip() and not line.startswith("#")]
    for event in events:
        assert set(event) == {"类别", "问题", "尝试", "现象", "决定", "依据"}
        if event["类别"] == "科学尝试":
            narrative = " ".join(event[key] for key in ["尝试", "现象", "决定", "依据"])
            assert not any(word in narrative for word in prohibited), narrative
        if not any(row.get("问题") == event["问题"] and row.get("尝试") == event["尝试"] for row in existing):
            existing.append(event)
    write(path, existing)



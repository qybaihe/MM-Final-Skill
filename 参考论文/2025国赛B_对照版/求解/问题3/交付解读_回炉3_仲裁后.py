def load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def timeout_handler(signum, frame):
    raise TimeoutError('交付核对达到120秒上限；已有核验结果保留，不写完成标记')


def edit(path, content):
    if time.monotonic() - STARTED > TIME_LIMIT - 5:
        raise TimeoutError('接近交付时间上限')
    relative = str(path.relative_to(ROOT))
    if path.exists():
        previous = path.read_text(encoding='utf-8')
        if previous == content:
            return
        patch = f'*** Begin Patch\n*** Update File: {relative}\n@@\n'
        patch += ''.join('-' + line + '\n' for line in previous.splitlines())
        patch += ''.join('+' + line + '\n' for line in content.splitlines())
    else:
        patch = f'*** Begin Patch\n*** Add File: {relative}\n'
        patch += ''.join('+' + line + '\n' for line in content.splitlines())
    subprocess.run(['apply_patch'], input=patch + '*** End Patch\n', text=True, check=True, cwd=ROOT, capture_output=True, timeout=15)


def edit_json(path, value):
    edit(path, json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n')


def lookup(value, path):
    for component in path.split('/'):
        value = value[int(component)] if isinstance(value, list) else value[component]
    return value



def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def patch_text(path, content):
    if time.monotonic() - START >= 80:
        raise TimeoutError("交付软截止，保留已完成文件")
    target = ROOT / path
    previous = target.read_text(encoding="utf-8") if target.exists() else ""
    if previous == content:
        return
    if target.exists():
        differences = list(difflib.unified_diff(previous.splitlines(keepends=True),
                                              content.splitlines(keepends=True), n=3))
        body = re.sub(r"^@@[^\n]*\n", "@@\n", "".join(differences[2:]), flags=re.M)
        patch = f"*** Begin Patch\n*** Update File: {path}\n{body}*** End Patch\n"
    else:
        body = "".join("+" + line + "\n" for line in content.splitlines())
        patch = f"*** Begin Patch\n*** Add File: {path}\n{body}*** End Patch\n"
    subprocess.run(["apply_patch"], input=patch, text=True, check=True, cwd=ROOT, timeout=30)


def patch_json(path, payload):
    patch_text(path, json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False) + "\n")


def at(path, key):
    value = load(path)
    for token in re.sub(r"\[(\d+)\]", r".\1", key).split("."):
        value = value[int(token)] if isinstance(value, list) else value[token]
    return value



def 归一(路径: str) -> str:
    """把带编号的实例路径归一成契约模式：结果声明_问题1.json → 结果声明_问题N.json。

    门检里既有字面量（"交接/题面契约.json"）也有 f-string（f"交接/红队_问题{编号}.json"），
    后者经 AST 取值后形如 交接/红队_问题X.json；两者要落到同一个契约键上。
    """
    import re
    s = re.sub(r"\{[^}]*\}", "N", 路径)      # f-string 占位
    # glob 模式（审稿/硬伤_轮*.json）与 f-string 取值（…问题X.json）要落到同一契约键
    s = re.sub(r"(?<=问题)[0-9X*]+", "N", s)
    s = re.sub(r"(?<=轮)[0-9X*]+", "N", s)
    s = re.sub(r"(?<=_)[0-9]+(?=\.)", "N", s)
    return s


def 查(路径: str):
    """按归一后的路径取登记项；未登记返回 None（核对器据此报「未登记契约」）。"""
    return 契约表.get(归一(路径))

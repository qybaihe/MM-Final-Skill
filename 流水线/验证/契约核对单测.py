#!/usr/bin/env python3
"""契约核对器自测（M4-6 验收）——纯本地，不依赖容器。

为什么核对器本身需要单测：它的价值全在**判得准**。
构建过程中它连出三个错，每一个都会把人引向错误的修法：
  · 模块级绑定 → 把题面契约的 需求号/内容 误报成 假设台账 未声明（变量名跨门复用）；
  · 平铺遍历推导式 → 把本地键 有证据 误报成仲裁契约字段；
  · 只认字面量键 → 把 `it.get(k)`（k 是循环变量）整组字段静默漏掉。
前两个会**逼人往 schema 里补假字段**——那正是这条测试要防的事；第三个是盲区。
本单测把这三个形状全部钉死。

用法：python3 契约核对单测.py
"""
import pathlib
import shutil
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import 契约核对 as 核                                    # noqa: E402

根 = pathlib.Path(tempfile.mkdtemp())
核.线 = 根                                               # 夹具目录顶替流水线根
(根 / "角色").mkdir()

结果 = []


def 断言(名, 成立, 说明):
    结果.append(成立)
    print(f"{'✓' if 成立 else '✗'} {名}\n    {说明}")


def 写(相对, 文本):
    p = 根 / 相对
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(文本, encoding="utf-8")
    return p


def 跑(消费源, 表):
    p = 写("夹具门检.py", 消费源)
    return {r["契约"]: r for r in 核.核对(门检路径=str(p), 表=表)[0]}


# ---------------------------------------------------------------- 夹具：生产方
写("角色/甲.md", '''## 产出 `交接/甲_问题X.json`（schema 严格照此）

```json
{"问题": 1, "核心指标": {"厚度": 1.0}, "口径说明": {"厚度": "μm"}}
```
''')
写("角色/乙.md", '''产出 `交接/乙_问题X.json`（schema 严格照此）：
```json
{"逐项": [{"指标": "x", "应改方": "建模", "消解状态": "", "消解证据": ""}], "总裁定": "..."}
```
''')
写("代码产出.py", '''
report = {}
过精 = []
过精.append({"文件": "a", "数字": "1.0"})
report["有效数字"] = {"过精数量": 1, "明细": 过精[:30]}
声明 = {"结论": "未复算", "跳过原因": "预算耗尽"}
''')

表甲 = {"交接/甲_问题N.json": {"生产": "角色/甲.md", "声明": 核.围栏}}


# ---------------------------------------------------------------- 1. 核心：读了没声明的字段
r = 跑('''
def G(编号):
    声明 = 读json(f"交接/甲_问题{编号}.json")
    a = 声明.get("核心指标")
    b = 声明.get("跳过原因")
''', 表甲)
断言("★ 消费方读未声明字段 → 判失败",
     r["交接/甲_问题N.json"]["态"] == "缺字段"
     and r["交接/甲_问题N.json"]["缺"] == ["跳过原因"],
     "这正是 20260831 探到的两处的形状（跳过原因 / 有效数字），"
     "也是今后最常见的失效模式——两处都是我一边思考契约漂移一边亲手制造的")

r = 跑('''
def G(编号):
    声明 = 读json(f"交接/甲_问题{编号}.json")
    a = 声明.get("核心指标")
''', 表甲)
断言("字段全部有声明 → 通过",
     r["交接/甲_问题N.json"]["态"] == "通过",
     "正常路径不该误伤")


# ---------------------------------------------------------------- 2. 三个真实假阳性/漏报
r = 跑('''
def G0():
    契约 = 读json("交接/甲_问题1.json")
    for 项 in 契约.get("核心指标"):
        x = 项.get("厚度")

def G2(编号):
    台账 = 读json("交接/乙_问题1.json")
    for x in 台账.get("逐项"):
        y = x.get("指标")
''', {**表甲, "交接/乙_问题N.json": {"生产": "角色/乙.md", "声明": 核.围栏}})
断言("★ 变量名跨函数复用不串味",
     r["交接/乙_问题N.json"]["态"] == "通过" and r["交接/甲_问题N.json"]["态"] == "通过",
     "G0 与 G2 都用 x/项 这类名字。模块级绑定会把一边的字段记到另一边头上——"
     "首版就把题面契约的 需求号/内容/评分点推测 误报成假设台账未声明")

r = 跑('''
def G(编号):
    仲 = 读json(f"交接/乙_问题{编号}.json")
    未决 = []
    for x in 仲.get("逐项"):
        未决.append({"指标": x.get("指标"), "有证据": True})
    缺证 = [x["指标"] for x in 未决 if not x["有证据"]]
''', {"交接/乙_问题N.json": {"生产": "角色/乙.md", "声明": 核.围栏}})
断言("★ 推导式自带作用域，本地键不算契约字段",
     r["交接/乙_问题N.json"]["态"] == "通过",
     "`[x[…] for x in 未决]` 里的 x 是推导式自己的变量，外层同名 x 恰好绑在契约上。"
     "平铺遍历会把本地键 有证据 记成契约的未声明字段 → 逼人补一个假字段进 schema")

r = 跑('''
def G(编号):
    台账 = 读json(f"交接/乙_问题{编号}.json")
    for it in 台账.get("逐项"):
        for k in ("指标", "应改方", "消解状态"):
            if not str(it.get(k, "")).strip():
                pass
''', {"交接/乙_问题N.json": {"生产": "角色/乙.md", "声明": 核.围栏}})
断言("★ 循环变量当键也算读取",
     r["交接/乙_问题N.json"]["读"] == 4,     # 逐项 + 元组里的 3 个键

     "门检 G2 检查假设台账就是 `it.get(k)` 这么写的。只认字面量键会把整组字段"
     "静默漏掉——漏报比误报安全，但仍是盲区")


# ---------------------------------------------------------------- 3. 容错键与双生产方
r = 跑('''
def G(编号):
    仲 = 读json(f"交接/乙_问题{编号}.json")
    for x in 仲.get("逐项"):
        消 = x.get("消解状态") or x.get("消解")
''', {"交接/乙_问题N.json": {"生产": "角色/乙.md", "声明": 核.围栏,
                             "容错": {"消解": "消解状态"}}})
断言("容错键不判失败，但要显式登记",
     r["交接/乙_问题N.json"]["态"] == "通过"
     and r["交接/乙_问题N.json"]["容错命中"] == ["消解"],
     "消解/证据 是**读侧宽容**不是生产方字段——写进围栏会让腿以为要输出两套键")

r = 跑('''
def G(编号):
    红 = 读json(f"交接/甲_问题{编号}.json")
    a = 红.get("核心指标")
    b = 红.get("跳过原因")
''', {"交接/甲_问题N.json": {"生产": "角色/甲.md", "声明": 核.围栏,
                             "另产": {"生产": "代码产出.py", "声明": 核.代码, "写入": "声明"}}})
断言("★ 双生产方取并集",
     r["交接/甲_问题N.json"]["态"] == "通过",
     "红队_问题N.json 正常路径由腿写、预算耗尽时由驱动代写『未复算』。"
     "各自声明各自那部分，不必把 跳过原因 挤进腿的 schema（腿看见就可能去填，等于开逃工口子）")


# ---------------------------------------------------------------- 4. 代码产出契约
r = 跑('''
def G():
    审计 = 读json("审稿/丙.json")
    a = 审计.get("有效数字")
    b = a.get("明细")
    c = b.get("数字")
    d = a.get("过精数量")
''', {"审稿/丙.json": {"生产": "代码产出.py", "声明": 核.代码, "写入": "report"}})
断言("代码产出：schema 即写入语句，含中转列表",
     r["审稿/丙.json"]["态"] == "通过",
     "`过精.append({'数字':…})` → `report['有效数字']['明细']`。不追这一层中转，"
     "真产出的 数字 会被误报；而要求脚本另抄一份 schema 常量就是第二事实来源")


# ---------------------------------------------------------------- 5. 未登记必须报
r = 跑('''
def G():
    x = 读json("交接/查无此契约.json")
    y = x.get("啥")
''', 表甲)
断言("未登记契约必须报出",
     r["交接/查无此契约.json"]["态"] == "未登记",
     "门检消费了却没登记，说明契约表漏了——不能静默放过")


# ---------------------------------------------------------------- 6. 路径归一
断言("归一：字面量/f-string/glob 落到同一契约键",
     核.归一("交接/红队_问题1.json") == 核.归一("交接/红队_问题X.json")
     == 核.归一("交接/红队_问题{编号}.json") == "交接/红队_问题N.json"
     and 核.归一("审稿/硬伤_轮*.json") == "审稿/硬伤_轮N.json",
     "门检里三种写法都有；glob 通配也要归一，否则 硬伤_轮*.json 会被判成未登记")

shutil.rmtree(根, ignore_errors=True)
print("=" * 74)
print(f"{sum(结果)}/{len(结果)} 通过")
sys.exit(0 if all(结果) else 1)

#!/usr/bin/env python3
"""审计单测（M5-1）：对一份手造的小论文跑真实 bin/审计.py，断言表达画像/段级溯源/自造缩写/图题/记录分流/问题重述各节的关键值。
覆盖的实测缺陷：10^{4} 上标被数成 104、\\FloatBarrier 命令名被判自造缩写、工作根残留旧章污染统计、键路径嵌套未命中。
用法：python3 审计单测.py
"""
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

线 = pathlib.Path(__file__).resolve().parent.parent
根 = pathlib.Path(tempfile.mkdtemp(prefix="审计单测_"))
for d in ("bin", "运行时", "论文", "求解/问题1/结果", "交接", "审稿"):
    (根 / d).mkdir(parents=True, exist_ok=True)
for n in ("审计.py", "表达画像.py"):
    shutil.copy(线 / "运行时" / n, 根 / "bin" / n)
for n in ("禁用词.txt", "内部术语.txt", "对冲词.txt", "缩写白名单.txt", "流程词.txt", "表达阈值.json"):
    shutil.copy(线 / "运行时" / n, 根 / "运行时" / n)
# 阈值用内联夹具：真稿校准（验证/范文分布.py）会改 运行时/表达阈值.json（20260908 硬线 4→10），
# 单测断言的是审计逻辑不是阈值本身，所以固定一份先验值，与 门检单测 同做法。
(根 / "运行时/表达阈值.json").write_text(json.dumps({"出处": "审计单测内联夹具（先验：段内数字 硬线 4/软线 2）",
    "数字密度_上限": {"摘要": 30.0, "首读章": 30.0, "正文章": 35.0}, "对冲密度_上限": {"摘要": 8.0, "首读章": 6.0, "正文章": 6.0},
    "句均汉字_上限": {"摘要": 40.0, "首读章": 45.0, "正文章": 48.0},
    "摘要画像": {"数字个数_上限": 12, "对冲个数_上限": 3, "缩写个数_上限": 0, "句均汉字_上限": 40.0},
    "段内数字": {"硬线": 4, "软线": 2}, "段首数字": 0}, ensure_ascii=False), encoding="utf-8")
W = lambda p, s: (根 / p).write_text(s, encoding="utf-8")
J = lambda p, o: (根 / p).write_text(json.dumps(o, ensure_ascii=False, indent=1), encoding="utf-8")

J("求解/问题1/结果/核心.json", {"厚度均值": 10.52, "基线差": 3.1, "灵敏度": {"折射率": {"变化率": 2.1}}, "样本": {"点数": 7469}})
J("交接/实验记录.json", [
    {"类别": "科学尝试", "问题": 1, "尝试": "最小二乘直接拟合", "现象": "双峰", "决定": "改谱峰配对", "依据": "求解结果:残差"},
    {"类别": "科学尝试", "问题": 1, "尝试": "按任务单返工加密网格", "现象": "误差降 3%", "决定": "保留", "依据": "结果"},
    {"类别": "流程事件", "问题": 1, "尝试": "改脚本名", "现象": "", "决定": "", "依据": ""},
    {"问题": 1, "尝试": "换核函数", "现象": "略好", "决定": "保留", "依据": "结果"}])
W("论文/论文.tex", "\\documentclass{format}\n\\begin{document}\n\\input{0.摘要.tex}\n\\input{1.问题重述与总体分析.tex}\n\\input{4.模型的建立与求解.tex}\n\\input{99.附录.tex}\n\\end{document}\n")
W("论文/0.摘要.tex", "\\begin{abstract}\n红外光在薄膜两个界面反射后互相干涉，条纹的疏密里藏着厚度。本文从两组反射光谱里把厚度读出来。\n"
  "\\textbf{对于问题一：}外延层厚度为 10.52 微米，两角相差不到半微米。\n% src:求解/问题1/结果/核心.json:厚度均值\n\\end{abstract}\n\\keywords{干涉}\n\\label{abstract:end}\n")
W("论文/1.问题重述与总体分析.tex", "\\section{问题重述与总体分析}\n\\subsection{问题重述}\n题目给定了两组反射光谱（附件 1、2）与折射率公式，要求建立由光谱确定厚度的模型并给出可靠性。\n"
  "\\subsection{总体分析}\n全文思路见图~\\ref{fig:idea}。\n\\begin{figure}\\centering\\includegraphics[width=0.8\\textwidth]{../求解/问题1/图片/思路.png}\\caption{全文求解思路}\\end{figure}\n")
W("论文/4.模型的建立与求解.tex", "\\section{模型的建立与求解}\n\\subsection{问题一的建模与求解：证据门判定}\n\\FloatBarrier\n"
  # 段 A：段级溯源通过（两个数字都在池里）
  "外延层厚度为 10.52 微米，比基线低 3.1\\%。折射率扰动两成，厚度只变 2.1\\%。\n% src:求解/问题1/结果/核心.json:厚度均值;基线差;灵敏度.折射率.变化率\n\n"
  # 段 B：存疑（99.9 不在池里）
  "另一组数据给出 99.9 微米。\n% src:求解/问题1/结果/核心.json:厚度均值\n\n"
  # 段 C：无源段（有统计数字、没有 src）
  "样本共有 7469 个波数点，覆盖范围足够。\n\n"
  # 段 D：段首数字 + 上标不计数 + 自造缩写 DOP + 键路径回退（样本.点数 写成 点数）
  "10.52 微米这一估计在 $10^{4}$ 量级的点数下稳定，DOP 指标为 0.87。\n% src:求解/问题1/结果/核心.json:厚度均值;点数\n\n"
  # 段 E：超预算段（6 个统计数字）
  "各角度的厚度分别为 10.52、10.49、10.61、10.55、10.47 与 10.58 微米。\n% src:求解/问题1/结果/核心.json:厚度均值\n\n"
  "\\begin{figure}\\centering\\includegraphics[width=0.8\\textwidth]{../求解/问题1/图片/q1.png}\\caption{三问关键风险与置信表述}\\end{figure}\n"
  "\\begin{figure}\\centering\\includegraphics[width=0.8\\textwidth]{../求解/问题1/图片/q2.png}\\caption{两入射角下厚度估计随波数的收敛}\\end{figure}\n")
W("论文/_旧版第4章.tex", "\\section{旧章}\n这是残留的旧版章节，含禁用词 综上所述 与 ZZZ 缩写 与 9999 个数字。\n")
W("论文/7.未挂载.tex", "\\section{未挂载}\n没有被 论文.tex input 的章：QQQ 缩写与 8888。\n")
W("论文/99.附录.tex", "\\section{附录}\n\\begin{lstlisting}\nprint(1)\n\\end{lstlisting}\n")

r = subprocess.run([sys.executable, "bin/审计.py"], cwd=根, capture_output=True, text=True, timeout=300)
报 = json.loads((根 / "审稿/审计报告.json").read_text(encoding="utf-8"))
失败 = []


def 期望(名, 条件, 实际=""):
    print(f"{'✓' if 条件 else '✗'} {名}{'' if 条件 else f'  实际={实际}'}")
    if not 条件:
        失败.append(名)


画 = 报["表达画像"]
章 = 画["按章"]
期望("只审 论文.tex 挂载的章（_旧版/未挂载 不进账）", set(章) == {"论文/0.摘要.tex", "论文/1.问题重述与总体分析.tex", "论文/4.模型的建立与求解.tex"}, sorted(章))
第四 = 章["论文/4.模型的建立与求解.tex"]
期望("上标 10^{4} 整体不计为统计数字（第4章数字个数=13）", 第四["数字个数"] == 13, 第四["数字个数"])
期望("段首数字段=1（段 D）", 画["段首数字段"] == 1 and 画["段首数字明细"][0]["开头"].startswith("10.52"), (画["段首数字段"], 画["段首数字明细"]))
期望("超预算段=1（段 E，6 个数字 > 硬线 4）", 画["超预算段"] == 1 and 画["超预算段明细"][0]["数字个数"] == 6, 画["超预算段明细"])
期望("摘要画像有文件且缩写=0", 画["摘要画像"].get("文件") == "论文/0.摘要.tex" and 画["摘要画像"]["缩写个数"] == 0, 画["摘要画像"])
期望("阈值出处非缺失", 画["阈值出处"] and 画["阈值出处"] != "缺失", 画["阈值出处"])
溯 = 报["溯源核验"]
期望("段级溯源：段 A/D/E+摘要 通过、段 B 存疑 99.9", 溯["核对通过"] == 4 and 溯["存疑数"] == 1 and 溯["存疑明细"][0]["数字"] == [99.9], (溯["核对通过"], 溯["存疑明细"]))
期望("键路径回退：点数 命中 样本.点数（键未命中=0）", 溯["键未命中数"] == 0, 溯.get("键未命中明细"))
数 = 报["数字溯源"]
期望("无源段=1（段 C）且覆盖率 5/6", 数["无源段"] == 1 and abs(数["覆盖率"] - 0.83) < 0.01, 数)
缩 = 报["自造缩写"]
期望("自造缩写只有 DOP（FloatBarrier 不算）", 缩["去重"] == ["DOP"], 缩["去重"])
期望("标题违规：证据门（内部术语）", 缩["标题违规数"] == 1 and 缩["标题违规"][0]["词"] == "证据门", 缩["标题违规"])
图 = 报["图题"]
期望("图题对冲违规=1（置信）", 图["图题数"] == 3 and 图["对冲违规数"] == 1 and "置信" in 图["对冲违规"][0]["词"], 图)
记 = 报["实验记录分流"]
期望("记录分流：2 科学/1 流程/1 未分类/1 含流程词", (记["科学尝试"], 记["流程事件"], 记["未分类"], 记["科学尝试含流程词"]) == (2, 1, 1, 1), 记)
重 = 报["问题重述"]
期望("问题重述五要素全 True", all(重[k] for k in ("有章", "含给定", "含要求", "有总体分析", "有思路图")), 重)
期望("禁用词不被残留旧章污染（=0）", 报["禁用词"]["数量"] == 0, 报["禁用词"])
print(f"\n{'全部通过' if not 失败 else f'失败 {len(失败)} 项：{失败}'}  （夹具目录 {根}）")
if 失败:
    print("stderr 尾：", r.stderr[-800:])
sys.exit(0 if not 失败 else 1)

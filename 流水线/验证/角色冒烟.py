    print(f"\n===== 冒烟 {名} =====")
    h.exec(f"rm -f 日志/{腿名}.done", quiet=True)
    h.leg(角色, 任务, 腿名, sync=False, leg_timeout=2700)
    t0 = time.time()
    while time.time() - t0 < 2700:
        time.sleep(30)
        d = h.exec(f"[ -f 日志/{腿名}.done ] && cat 日志/{腿名}.done", quiet=True)
        if (d.get("stdout") or "").strip():
            print(f"  done@{int(time.time()-t0)}s: {(d.get('stdout') or '').strip()[:300]}")
            break
    else:
        print("  !! 超时未完成")
    d = h.exec(" ; ".join([f"echo '--- {p} ---'; (head -c 1800 {p} 2>/dev/null || echo 缺失)" for p in 产物]), quiet=True)
